/**
 * Convert hex string color map to numeric format for BlockRegistry
 * @returns {Object} Map of block names (without minecraft:) to hex numbers
 */
export function getBlockColorsNumeric() {
  const result = {};
  for (const [name, hexStr] of Object.entries(BLOCK_COLORS)) {
    // Strip minecraft: prefix for BlockRegistry compatibility
    const shortName = name.replace('minecraft:', '');
    // Parse hex string to number (handle both #RRGGBB and #RRGGBBAA)
    const hex = hexStr.replace('#', '');
    // Only use RGB portion (first 6 chars)
    const rgbHex = hex.substring(0, 6);
    result[shortName] = parseInt(rgbHex, 16);
  }
  return result;
}

